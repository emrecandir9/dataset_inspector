from backend.core.models import DatasetReport
from backend.reports.markdown_report import export_markdown


def export_html(report: DatasetReport, output_path: str | None = None) -> str:
    """Export report as standalone HTML.
    
    For V1, generates a clean HTML wrapper around the markdown content.
    
    Args:
        report: The complete dataset report.
        output_path: Optional path to save the HTML file.
        
    Returns:
        HTML string.
    """
    md_content = export_markdown(report)
    
